/** P0021 S88a. Derived artifact only: docs/Grammatik.pegjs -> src/js/parser.mjs.
 * Run with --check in CI, or --write explicitly to regenerate.
 * No localization, runtime semantics, or grammar changes live here.
 */
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import peggy from 'peggy';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const grammarPath = path.join(root, 'docs/Grammatik.pegjs');
const generatedPath = path.join(root, 'src/js/parser.mjs');
const args = process.argv.slice(2);
if (args.length !== 1 || !['--check', '--write'].includes(args[0])) {
  console.error('Usage: node tools/build/generate_canonical_parser.mjs --check|--write');
  process.exitCode = 2;
} else {
  const grammar = readFileSync(grammarPath, 'utf8');
  // Peggys source mode avoids executing the grammar at build time.
  const generated = peggy.generate(grammar, {format: 'es', output: 'source'});
  const normalize = source => source.replace(/\r\n/g, '\n');
  const current = existsSync(generatedPath) ? readFileSync(generatedPath, 'utf8') : null;
  const matched = current !== null && normalize(current) === normalize(generated);
  if (args[0] === '--check') {
    if (matched) {
      console.log('P0021 S88a: canonical grammar and generated parser are synchronized.');
    } else {
      console.error('P0021 S88a: parser drift detected. Regenerate explicitly with --write, review git diff.');
      process.exitCode = 1;
    }
  } else if (matched) {
    console.log('P0021 S88a: generated parser already synchronized; no write required.');
  } else {
    if (current !== null &&
        (!current.includes('peg$parse') || !/generated by Peggy/i.test(current))) {
      throw new Error('Refusing to replace an unrecognized generated parser. Review file first.');
    }
    // Backup is handled by the review/verification script, NOT silently here.
    writeFileSync(generatedPath, generated, 'utf8');
    console.log('P0021 S88a: regenerated src/js/parser.mjs from docs/Grammatik.pegjs.');
  }
}
